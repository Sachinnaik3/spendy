@app.route("/profile")
def profile():
    user_id = session.get("user_id")
    if user_id is None:
        return redirect(url_for("login"))

    user = get_user_by_id(user_id)
    if user is None:
        session.clear()
        return redirect(url_for("login"))

    joined = datetime.strptime(user["created_at"], "%Y-%m-%d %H:%M:%S").strftime("%d %b %Y")
    summary = get_expense_summary(user_id)
    return render_template("profile.html", user=user, joined=joined, summary=summary)


